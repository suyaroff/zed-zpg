-- Демо-схема zpg_demo: на ней построены все примеры руководства (docs/ru).
--
-- Как создать:
--   * в Zed: откройте этот файл, выделите всё (ctrl-a) → ctrl-. → «zpg: Run selection on …»;
--     если подключений несколько, допишите первой строкой  -- @conn имя
--   * или из терминала:  psql -d ваша_база -f docs/examples/demo.sql
--
-- Первый запрос удаляет и пересоздаёт только схему zpg_demo, поэтому файл
-- можно запускать повторно, чтобы вернуть данные к исходным. zpg спросит
-- подтверждение перед DROP — это ожидаемо.
-- Удалить демо целиком:  DROP SCHEMA zpg_demo CASCADE;

DROP SCHEMA IF EXISTS zpg_demo CASCADE;
CREATE SCHEMA zpg_demo;

CREATE TYPE zpg_demo.order_status AS ENUM ('new', 'paid', 'shipped', 'cancelled');

CREATE TABLE zpg_demo.customers (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      text NOT NULL UNIQUE,
    name       text NOT NULL,
    city       text,
    vip        boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    note       text
);

CREATE TABLE zpg_demo.products (
    id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku    text NOT NULL UNIQUE,
    title  text NOT NULL,
    price  numeric(10, 2) NOT NULL CHECK (price >= 0),
    tags   text[] NOT NULL DEFAULT '{}',
    attrs  jsonb,
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE zpg_demo.orders (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES zpg_demo.customers ON DELETE CASCADE,
    status      zpg_demo.order_status NOT NULL DEFAULT 'new',
    created_at  timestamptz NOT NULL DEFAULT now(),
    total       numeric(12, 2) NOT NULL DEFAULT 0,
    comment     text
);
CREATE INDEX orders_customer_idx ON zpg_demo.orders (customer_id);
CREATE INDEX orders_open_idx ON zpg_demo.orders (created_at) WHERE status IN ('new', 'paid');

CREATE TABLE zpg_demo.order_items (
    order_id   bigint NOT NULL REFERENCES zpg_demo.orders ON DELETE CASCADE,
    product_id integer NOT NULL REFERENCES zpg_demo.products,
    qty        integer NOT NULL CHECK (qty > 0),
    price      numeric(10, 2) NOT NULL,
    amount     numeric(12, 2) GENERATED ALWAYS AS (qty * price) STORED,
    PRIMARY KEY (order_id, product_id)
);

-- Без первичного ключа: zpg покажет её только для чтения.
CREATE TABLE zpg_demo.events (
    at      timestamptz NOT NULL DEFAULT now(),
    level   text NOT NULL,
    message text NOT NULL,
    payload jsonb
);

-- orders.total всегда равен сумме позиций.
CREATE FUNCTION zpg_demo.recalc_total() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE zpg_demo.orders o
    SET total = coalesce((SELECT sum(amount) FROM zpg_demo.order_items i WHERE i.order_id = o.id), 0)
    WHERE o.id = coalesce(NEW.order_id, OLD.order_id);
    RETURN NULL;
END $$;
CREATE TRIGGER order_items_total
    AFTER INSERT OR UPDATE OR DELETE ON zpg_demo.order_items
    FOR EACH ROW EXECUTE FUNCTION zpg_demo.recalc_total();

CREATE VIEW zpg_demo.paid_orders AS
SELECT o.id, c.name AS customer, o.total, o.created_at
FROM zpg_demo.orders o
JOIN zpg_demo.customers c ON c.id = o.customer_id
WHERE o.status IN ('paid', 'shipped');

COMMENT ON TABLE zpg_demo.customers IS 'Покупатели интернет-магазина';
COMMENT ON COLUMN zpg_demo.customers.vip IS 'Скидка 10% на все заказы';
COMMENT ON COLUMN zpg_demo.orders.total IS 'Считается триггером order_items_total';
COMMENT ON COLUMN zpg_demo.order_items.amount IS 'qty * price, generated';

